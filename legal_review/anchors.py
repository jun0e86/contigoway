"""anchors.py

상황 문장에 특정 낱말이 있으면, 판례·해석례 검색 결과와 별개로 '먼저 확인할 대표 조문'을 함께 찾아온다.

왜 필요한가
  판례·해석례를 먼저 찾고 거기서 인용된 조문을 뽑는 구조라서, 형사 판례가 상위에 오면
  벌칙·양벌규정 조문만 나오고 정작 핵심 조문(예: 진료기록 열람)은 빠질 수 있다.

주의
  - 여기에는 조문 '번호'만 적는다. 조문 제목과 원문은 국가법령정보 API에서 조회해서 보여주므로,
    번호를 잘못 적으면 엉뚱한 제목이 보이거나 '조문을 찾지 못했습니다'로 나온다.
    바꾸거나 추가한 뒤에는 검색 화면에서 조문 제목이 의도한 것과 맞는지 꼭 확인할 것.
  - 이 목록은 업무 상황에 맞게 직접 고쳐 쓰는 설정이다. 법률 자문이 아니다.
  - 순서가 앞선 묶음의 조문이 먼저 나오고, 전체는 MAX_ANCHORS개까지만 붙는다.
"""
from __future__ import annotations

ANCHORS = [
    # (상황 문장에 이 낱말 중 하나라도 있으면,  함께 찾아올 조문들)
    (("진료기록", "열람", "사본", "보호자", "가족", "대리인", "대리수령"),
     ["의료법 제21조", "의료법 제22조"]),

    (("누설", "비밀", "알려", "공개", "유출", "공유"),
     ["의료법 제19조"]),

    (("동의", "제3자", "제공", "개인정보", "민감정보", "유출", "공유"),
     ["개인정보 보호법 제17조", "개인정보 보호법 제23조"]),
]

MAX_ANCHORS = 4


def match_anchor_refs(text: str) -> list[str]:
    """상황 문장에 걸리는 대표 조문 목록 (중복 제거, 최대 MAX_ANCHORS개)."""
    text = text or ""
    refs: list[str] = []
    for triggers, laws in ANCHORS:
        if any(t in text for t in triggers):
            for ref in laws:
                if ref not in refs:
                    refs.append(ref)
    return refs[:MAX_ANCHORS]
